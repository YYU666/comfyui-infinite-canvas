import assert from 'node:assert/strict';
import { planCanvasConnection, resolveConnectionSource } from './src/canvas-connections.js';
const media=(id,kind='image',extra={})=>({id,type:'media',data:{kind,url:`/${id}.png`,...extra}});
const gen=(id,mode='qwenEdit',extra={})=>({id,type:'generator',data:{mode,status:'idle',...extra}});
const image=media('image'), video=media('video','video'), mask=media('mask','image',{mediaRole:'mask'}), qwen=gen('qwen'), frames=gen('frames','frames');
const nodes=[image,video,mask,qwen,frames];
const superResolution=gen('sr','videoSuperResolution');
assert.equal(planCanvasConnection({source:'video',target:'sr',sourceHandle:'ref',targetHandle:'guide'},[...nodes,superResolution],[]).connection.targetHandle,'guide');
for (const [source,targetHandle] of [['image','guide'],['mask','guide'],['video','references'],['video','identity']]) {
  assert.ok(planCanvasConnection({source,target:'sr',sourceHandle:'ref',targetHandle},[...nodes,superResolution],[]).error);
}
const conn=(source,target,handle,sourceHandle='ref')=>({source,target,targetHandle:handle,sourceHandle});
const plan=(c,n=nodes,e=[],o={})=>planCanvasConnection(c,n,e,o);
assert.equal(plan(conn('image','qwen','references')).source.id,'image');
assert.equal(plan(conn('image','qwen','guide')).connection.targetHandle,'references');
assert.match(plan(conn('video','qwen','references')).error,/图片/);
assert.match(plan(conn('image','qwen','mask')).error,/遮罩/);
assert.match(plan(conn('mask','qwen','references','mask')).error,/遮罩端口/);
assert.equal(plan(conn('mask','qwen','mask','mask')).connection.sourceHandle,'mask');
assert.match(plan(conn('image','qwen','references'),nodes,[],{readOnly:true}).error,/不可编辑/);
assert.match(plan(conn('image','qwen','references'),[image,gen('qwen','qwenEdit',{status:'queued'})]).error,/正在生成/);
assert.equal(plan(conn('image','mask','guide'),nodes,[{source:'mask',target:'qwen',targetHandle:'mask'}]).error,undefined);
assert.match(plan(conn('image','mask','guide'),[...nodes.filter(n=>n.id!=='qwen'),gen('qwen','qwenEdit',{status:'running'})],[{source:'mask',target:'qwen',targetHandle:'mask'}]).error,/底图/);
assert.equal(plan(conn('image','frames','first')).connection.targetHandle,'first');
assert.match(plan(conn('video','frames','first')).error,/类型/);
const ten=Array.from({length:10},(_,i)=>media(`r${i}`));
assert.match(plan(conn('image','qwen','references'),[...nodes,...ten],ten.map(n=>({source:n.id,target:'qwen',targetHandle:'references'}))).error,/10/);
const renderer=gen('renderer','image',{resultUrl:'/current.png'});
const old=media('old','image',{output:true,sourceGeneratorId:'renderer',url:'/old.png'});
const current=media('current','image',{output:true,sourceGeneratorId:'renderer',url:'/current.png'});
const rendered=[...nodes,renderer,old,current];
assert.equal(plan(conn('renderer','qwen','references','image'),rendered).source.id,'current');
assert.equal(plan(conn('renderer','qwen','references','image'),rendered).connection.sourceHandle,'ref');
assert.match(plan(conn('renderer','qwen','references','video'),rendered).error,/唯一/);
assert.match(plan(conn('renderer','qwen','references','image'),[...rendered,{...current,id:'ambiguous'}]).error,/唯一/);
assert.match(plan(conn('renderer','qwen','references','image'),[...nodes,gen('renderer','image')]).error,/还没有生成/);
assert.match(plan(conn('renderer','qwen','references','image'),[...nodes,renderer,old]).error,/唯一/);
assert.equal(resolveConnectionSource(renderer,'image',[renderer,current],[]).source.id,'current');
const same={id:'already',source:'image',target:'frames',sourceHandle:'ref',targetHandle:'first'};
assert.equal(plan(conn('image','frames','first'),nodes,[same]).existing.id,'already');
const pack={id:'pack',type:'imageProcess',data:{mode:'channelPack',status:'idle'}};
const adjust={id:'adjust',type:'imageProcess',data:{mode:'colorAdjust',status:'idle'}};
const processNodes=[...nodes,pack,adjust];
assert.equal(plan(conn('image','pack','red'),processNodes).connection.targetHandle,'red');
assert.equal(plan(conn('image','adjust','guide'),processNodes).error,undefined);
assert.ok(plan(conn('video','pack','red'),processNodes).error);
assert.ok(plan(conn('image','pack','guide'),processNodes).error);
assert.ok(plan(conn('adjust','pack','red'),processNodes,[{source:'pack',target:'adjust',targetHandle:'guide'}]).error);
assert.match(plan(conn('image','pack','alpha'),[...nodes,{...pack,data:{...pack.data,status:'finishing'}}]).error,/正在生成/);
console.log('PASS canvas connection rules: types, busy/readonly, masks, limits, current saved result, ambiguity and reconnect');
