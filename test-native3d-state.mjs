import assert from 'node:assert/strict';
import {nativeParameters,nativeRunIdentity,nativeDeliveryState,nativeAssetUrl,NATIVE3D_PRESETS,nativeGeometryInputError} from './src/native3d.js';
import {planCanvasConnection} from './src/canvas-connections.js';
const alpha={parameters:{properties:{seed:{type:'integer',default:42,minimum:0},sampling:{type:'boolean',default:false},quality:{type:'string',enum:['fast','full'],default:'fast'}}}};
const beta={parameters:{properties:{resolution:{type:'integer',enum:[512,1024],default:512}}}};
assert.deepEqual(nativeParameters(alpha),{seed:42,sampling:false,quality:'fast'});
assert.deepEqual(nativeParameters(beta,{resolution:1024}),{resolution:1024});
assert.throws(()=>nativeParameters(beta,{seed:42}),/不支持/);
assert.throws(()=>nativeParameters(alpha,{seed:1.5}),/类型/);
assert.throws(()=>nativeParameters(alpha,{quality:'fake'}),/范围/);
assert.throws(()=>nativeParameters(alpha,{seed:-1}),/范围/);
const source={id:'source',type:'native3d',data:{assetPath:'assets/source.glb',operation:'analyze'}};
const target={id:'process',type:'native3d',data:{operation:'ai_lowpoly',adapterId:'alpha',nativeParameters:{seed:42},nativeJobId:'job-a'}};
const connection={source:'source',target:'process',sourceHandle:'model',targetHandle:'model'};
assert.equal(planCanvasConnection(connection,[source,target],[]).connection.sourceHandle,'model');
assert.ok(planCanvasConnection({...connection,targetHandle:'references'},[source,target],[]).error);
assert.ok(planCanvasConnection(connection,[source,target],[],{readOnly:true}).error);
assert.ok(planCanvasConnection(connection,[source,{...target,data:{...target.data,status:'running'}}],[]).error);
assert.ok(planCanvasConnection({...connection,target:'image'},[source,{id:'image',type:'generator',data:{}}],[]).error);
const identity=nativeRunIdentity(target,source); target.data.nativeRun={identity};
assert.equal(nativeDeliveryState(target,source,{id:'job-a'}),'current');
assert.equal(nativeDeliveryState(target,source,{id:'job-old'}),'skip');
assert.equal(nativeDeliveryState({...target,data:{...target.data,nativeDeliveredJobId:'job-a'}},source,{id:'job-a'}),'skip');
assert.equal(nativeDeliveryState(target,{...source,data:{assetPath:'assets/new.glb'}},{id:'job-a'}),'stale');
assert.equal(nativeDeliveryState({...target,data:{...target.data,adapterId:'beta'}},source,{id:'job-a'}),'stale');
assert.equal(nativeDeliveryState({...target,data:{...target.data,nativeParameters:{seed:8}}},source,{id:'job-a'}),'stale');
assert.equal(nativeAssetUrl('prj_1','../private.glb'),null);
assert.equal(nativeAssetUrl('prj_1','assets/safe.glb'),'/api/projects/prj_1/assets/safe.glb');
assert.equal(Object.keys(NATIVE3D_PRESETS).length,9);
assert.equal(NATIVE3D_PRESETS.model_image_to_3d[1].operation,'image_to_3d');
assert.equal(NATIVE3D_PRESETS.model_material_wear[1].operation,'material_wear');
console.log('NATIVE3D_STATE_OK schemas, ports, readiness protections, source/config snapshots, completed delivery dedup');

assert.equal(NATIVE3D_PRESETS.model_lod[1].operation,'source_lod');
assert.equal(NATIVE3D_PRESETS.model_lod_legacy[1].operation,'repair_lod');
const blocked={...source,data:{...source.data,nativeGeometryProvenance:true,metadata:{geometry:{status:'blocked'}}}};
assert.ok(nativeGeometryInputError(blocked,'uv'));
assert.ok(nativeGeometryInputError(blocked,'bake'));
assert.equal(nativeGeometryInputError(blocked,'repair_lod'),null);
assert.equal(nativeGeometryInputError({...blocked,data:{...blocked.data,metadata:{geometry:{status:'accepted'}}}},'uv'),null);
assert.ok(nativeGeometryInputError({...source,data:{...source.data,metadata:{operation:'ai_lowpoly',geometry:{status:'accepted'}}}},'uv'));
