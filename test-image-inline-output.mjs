import assert from 'node:assert/strict';
import { inlineImageView, compactInlineImages } from './src/image-inline-output.js';
import { resolveConnectionSource, planCanvasConnection } from './src/canvas-connections.js';
const generator={id:'g',type:'generator',data:{mode:'qwenEdit',status:'done',resultUrl:'/new.png'}};
const output=(id,url,prompt)=>({id,type:'media',position:{x:1000,y:1000},data:{kind:'image',output:true,url,sourceGeneratorId:'g',sourcePromptId:prompt}});
const nodes=[generator,output('old','/old.png','p1'),output('new','/new.png','p2'),{id:'target',type:'generator',data:{mode:'characterSheet'}}];
const edges=[{id:'preview',source:'g',target:'new',targetHandle:'preview'},{id:'frozen',source:'old',sourceHandle:'ref',target:'target',targetHandle:'guide'}];
const snapshot=JSON.stringify({nodes,edges});
const compact=compactInlineImages(nodes,edges,['g']);
assert.equal(JSON.stringify({nodes,edges}),snapshot,'pure preview does not mutate state');
assert.deepEqual(compact.compacted[0].backingIds,['old','new']);
assert.equal(compact.nodes[0].data.inlineImageOutputId,'new');
assert.deepEqual(compact.edges,edges,'canonical graph never rewired');
const view=inlineImageView(compact.nodes,edges);
assert.equal(view.nodes.find(n=>n.id==='old').hidden,true);
assert.equal(view.nodes.find(n=>n.id==='new').hidden,true);
assert.equal(view.edges[0].hidden,true);
assert.equal(view.edges[1].source,'g');
assert.equal(view.edges[1].sourceHandle,'image');
assert.equal(view.edges[1].label,'已锁定历史结果');
assert.equal(view.edges[1].id,'frozen');
assert.equal(resolveConnectionSource(compact.nodes[0],'image',compact.nodes,edges).source.id,'new');
const planned=planCanvasConnection({source:'g',sourceHandle:'image',target:'target',targetHandle:'guide'},compact.nodes,edges);
assert.equal(planned.connection.source,'new','new drag captures immutable current output');
const retry=compact.nodes.map(n=>n.id==='g'?{...n,data:{...n.data,status:'running',resultUrl:'/future.png'}}:n);
assert.equal(edges.find(e=>e.id==='frozen').source,'old','regeneration never mutates prior inputs');
assert.equal(retry.find(n=>n.id===edges[1].source).data.url,'/old.png');
const loaded=JSON.parse(JSON.stringify(compact));
assert.deepEqual(inlineImageView(loaded.nodes,loaded.edges),view,'reload preserves same projection and backing');
assert.equal(inlineImageView(loaded.nodes.filter(n=>n.id!=='g'),edges).nodes.find(n=>n.id==='old').hidden,undefined,'deleting owner reveals saved outputs');
const multiple=[...nodes,output('extra','/extra.png','p2')];
assert.equal(compactInlineImages(multiple,edges,['g']).compacted.length,0,'custom multi output remains explicit');
const video=nodes.map(n=>n.id==='new'?{...n,data:{...n.data,kind:'video'}}:n);
assert.equal(compactInlineImages(video,edges,['g']).compacted.length,0,'video unaffected');
assert.deepEqual(compactInlineImages(nodes,edges,['target']).nodes,nodes,'unknown unfinished rows remain unchanged');
assert.throws(()=>compactInlineImages(nodes,edges,[]));
console.log('IMAGE_INLINE_OUTPUT_OK projection/reload/immutable references/retry/delete-owner/multi-output/video');

// Production: using the generated image as a reference uploads it to input/workbench.
const prodOwner={id:'generator-mw6zdu1n-8ahbc',type:'generator',data:{mode:'characterSheet',status:'done',promptId:'e23e9707-13f3-48bd-827b-61be0feb5fdb',queueJobId:'job_f84793fbe76447339f584f8cd1caa4a2',resultUrl:'/api/comfy/view?filename=H3_CharacterSheet_front_body_00001_.png&type=output'}};
const prodOutput={id:'image-mw6zg5gk-dwpmo',type:'media',data:{kind:'image',output:true,url:'/api/comfy/view?filename=uploaded.png&subfolder=workbench&type=input',sourceGeneratorId:prodOwner.id,sourcePromptId:prodOwner.data.promptId,sourceQueueJobId:prodOwner.data.queueJobId}};
const prodNodes=[prodOwner,prodOutput];
const production=compactInlineImages(prodNodes,[],[prodOwner.id]);
assert.equal(production.compacted[0].outputId,prodOutput.id);
const reload=JSON.parse(JSON.stringify(production.nodes));
assert.equal(compactInlineImages(reload,[],[prodOwner.id]).compacted[0].outputId,prodOutput.id);
assert.equal(resolveConnectionSource(reload[0],'image',reload,[]).source.id,prodOutput.id);
assert.equal(reload[1].data.url,prodOutput.data.url,'stored reference URL is untouched');
const conflicting=prodNodes.map(n=>n.id===prodOutput.id?{...n,data:{...n.data,sourceQueueJobId:'job_other'}}:n);
assert.equal(compactInlineImages(conflicting,[],[prodOwner.id]).compacted.length,0);
const ambiguous=[...prodNodes,{...prodOutput,id:'image_second'}];
assert.equal(compactInlineImages(ambiguous,[],[prodOwner.id]).compacted.length,0);
const stale=reload.map(n=>n.id===prodOwner.id?{...n,data:{...n.data,promptId:'new_prompt',queueJobId:'new_job'}}:n);
assert.equal(compactInlineImages(stale,[],[prodOwner.id]).compacted.length,0);
console.log('IMAGE_INLINE_PRODUCTION_IDENTITY_OK output-to-input rewrite, reload, ambiguity and conflicting execution IDs');
