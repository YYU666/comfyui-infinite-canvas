import assert from 'node:assert/strict';
import { nodeFileLocation, revealProjectAsset } from './src/canvas-file-location.js';
const resolve = data => nodeFileLocation({ data }, 'prj_current');
assert.deepEqual(resolve({ assetPath: 'assets/current.mp4', output: true, filename: 'stale.mp4', remoteName: 'stale-input' }), { kind: 'project', projectId: 'prj_current', assetPath: 'assets/current.mp4' });
assert.deepEqual(resolve({ output: true, filename: 'generated.mp4', subfolder: 'videos' }), { kind: 'output', name: 'videos/generated.mp4' });
assert.deepEqual(resolve({ remoteName: 'uploaded.png' }), { kind: 'input', name: 'uploaded.png' });
assert.deepEqual(resolve({ resultUrl: '/view?filename=x.mp4&subfolder=videos&type=output' }), { kind: 'output', name: 'videos/x.mp4' });
assert.equal(resolve({ resultUrl: 'http://[' }), null);
assert.equal(resolve({}), null);
assert.equal(nodeFileLocation({ data: { assetPath: 'assets/x', output: true, filename: 'stale' } }), null);
let sent;
globalThis.fetch = async (url, options) => { sent = { url, options }; return { ok: true, json: async () => ({ ok: true }) }; };
await revealProjectAsset(resolve({ assetPath: 'assets/current.mp4' }));
assert.equal(sent.url, '/api/projects/prj_current/assets/reveal');
assert.equal(sent.options.method, 'POST');
assert.deepEqual(JSON.parse(sent.options.body), { assetPath: 'assets/current.mp4' });
globalThis.fetch = async () => ({ ok: false, json: async () => ({ message: '素材不存在。' }) });
await assert.rejects(revealProjectAsset(resolve({ assetPath: 'assets/missing' })), /素材不存在/);
console.log('canvas file location tests passed');
