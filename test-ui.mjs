import { chromium } from './test-browser.mjs';
import fs from 'node:fs';

const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:8790', { waitUntil: 'networkidle' });
await page.waitForSelector('.connection-pill.online', { timeout: 30000 });
await page.screenshot({ path: '../workbench-home.png', fullPage: true });
if (!await page.getByText('让想法动起来').isVisible()) throw new Error('Empty preview missing');
await page.getByRole('button', { name: '作品', exact: true }).click();
await page.waitForSelector('text=本地作品库');
await page.getByRole('button', { name: '模型', exact: true }).click();
await page.waitForSelector('text=MiniMax H3', { timeout: 10000 });
await page.screenshot({ path: '../workbench-models.png', fullPage: true });
await page.getByRole('button', { name: '创作', exact: true }).click();
await page.getByRole('button', { name: '图生视频', exact: true }).click();
await page.locator('input[type=file]').first().setInputFiles('../test-frame.png');
await page.locator('textarea').fill('镜头缓慢推进，画面中的绿色逐渐变成森林，微风吹过，自然声音');
await page.getByRole('button', { name: '1:1', exact: true }).click();
await page.locator('input[type=range]').fill('6');
await page.getByRole('button', { name: '高级设置' }).click();
await page.screenshot({ path: '../workbench-form.png', fullPage: true });
const promptResponse = page.waitForResponse(r => r.url().endsWith('/prompt') && r.request().method() === 'POST', { timeout: 30000 });
await page.getByRole('button', { name: /开始生成/ }).click();
const response = await promptResponse;
const body = await response.text();
if (!response.ok()) throw new Error(`Prompt rejected: ${body}`);
const cancelButton = page.getByRole('button', { name: /取消生成/ });
if (await cancelButton.isVisible()) await cancelButton.click();
else await page.evaluate(async () => { await fetch('http://127.0.0.1:8188/interrupt', { method: 'POST', headers: {'Content-Type':'application/json'}, body:'{}' }); });
await page.waitForTimeout(700);
await page.screenshot({ path: '../workbench-cancelled.png', fullPage: true });
const report = { title: await page.title(), promptStatus: response.status(), promptBody: JSON.parse(body), errors, screenshots: ['workbench-home.png','workbench-models.png','workbench-form.png','workbench-cancelled.png'] };
fs.writeFileSync('../ui_test_report.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
await browser.close();
if (errors.length) process.exit(2);
