const target = page.locator('.react-flow__node[data-id="main-h3"] .react-flow__handle.target.first');
const s = await source.boundingBox(), t = await target.boundingBox();
assert.ok(s && t, 'Connection handles visible');
await page.mouse.move(s.x + s.width / 2, s.y + s.height / 2);
await page.mouse.down();
await page.mouse.move(t.x + t.width / 2, t.y + t.height / 2, { steps: 20 });
await page.mouse.up();
await page.waitForTimeout(500);
assert.equal(await page.locator('.react-flow__edge').count(), 1, 'Image connected to first frame');
await page.getByLabel('画布项目名称').fill('本地画布持久化测试');
await page.waitForTimeout(800);
await page.screenshot({ path: '../canvas-connected.png', fullPage: true });
await page.reload({ waitUntil: 'networkidle' });
assert.equal(await page.locator('.h3-prompt').inputValue(), '一只橘猫在阳光工作室伸懒腰，镜头缓慢推近，自然环境声');
assert.equal(await page.locator('.react-flow__edge').count(), 1, 'Edge persisted after reload');
assert.equal(await page.getByLabel('画布项目名称').inputValue(), '本地画布持久化测试');
await page.locator('.image-node input[type=file]').setInputFiles('../test-frame.png');
const promptResponse = page.waitForResponse(r => r.url().endsWith('/prompt') && r.request().method() === 'POST', { timeout: 30000 });
await page.locator('.h3-node .node-generate').click();
const response = await promptResponse;
const body = await response.text();
assert.equal(response.status(), 200, `Prompt accepted: ${body}`);
const requestJson = JSON.parse(response.request().postData());
assert.equal(requestJson.prompt['17'].inputs.image, 'workbench/test-frame.png');
assert.deepEqual(requestJson.prompt['7'].inputs.first_frame, ['17', 0]);
const cancel = page.locator('.h3-node .node-generate.cancel');
if (await cancel.isVisible()) await cancel.click();
else await page.evaluate(async () => { await fetch('http://127.0.0.1:8188/interrupt', { method: 'POST', headers: {'Content-Type':'application/json'}, body:'{}' }); });
await page.waitForTimeout(600);
await page.getByRole('button', { name: '文本备注 分镜与设定' }).click();
assert.ok(await page.locator('.note-node').count() >= 2);
await page.getByRole('button', { name: /本地作品/ }).first().click();
await page.waitForSelector('.neo-library');
await page.locator('.neo-library > div:first-child button').click();
await page.screenshot({ path: '../canvas-tested.png', fullPage: true });
await page.getByRole('button', { name: '简易模式', exact: true }).click();
await page.waitForSelector('.app-shell');
await page.getByRole('button', { name: '画布模式', exact: true }).click();
await page.waitForSelector('.neo-app');
const imageCountBeforeDrop = await page.locator('.image-node').count();
await page.evaluate(() => {
  const bytes = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII='), c => c.charCodeAt(0));
  const transfer = new DataTransfer(); transfer.items.add(new File([bytes], 'drop-test.png', { type: 'image/png' }));
  document.querySelector('.react-flow__pane').dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true, cancelable: true, clientX: 500, clientY: 500 }));
});
await page.waitForTimeout(300);
assert.equal(await page.locator('.image-node').count(), imageCountBeforeDrop + 1, 'Dropped image creates a node');
const h3CountBeforeDoubleClick = await page.locator('.h3-node').count();
await page.locator('.react-flow__pane').dblclick({ position: { x: 1100, y: 100 } });
await page.waitForTimeout(300);
assert.equal(await page.locator('.h3-node').count(), h3CountBeforeDoubleClick + 1, 'Double click creates a generator');
const report = { title: await page.title(), nodesAfterTests: await page.locator('.react-flow__node').count(), promptStatus: response.status(), firstFrame: requestJson.prompt['7'].inputs.first_frame, persistence: true, dragDrop: true, doubleClickAdd: true, simpleModeRoundtrip: true, errors };
fs.writeFileSync('../canvas_test_report.json', JSON.stringify(report, null, 2));
