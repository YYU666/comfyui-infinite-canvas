import assert from 'node:assert/strict';
import {planCanvasConnection,resolveConnectionSource} from './src/canvas-connections.js';
const process={id:'processor',type:'native3d',data:{operation:'ai_lowpoly',status:'completed',nativeJobId:'job-live',resultAssetPath:'assets/low.glb'}};
const result={id:'actual-result',type:'native3d',data:{operation:'analyze',status:'completed',sourceJobId:'job-live',sourceNodeId:'processor',assetPath:'assets/low.glb'}};
const target={id:'uv',type:'native3d',data:{operation:'uv',status:'idle'}};
const connection={source:'processor',sourceHandle:'model',target:'uv',targetHandle:'model'};
const nodes=[process,result,target];
const valid=planCanvasConnection(connection,nodes,[]);
assert.equal(valid.connection.source,'actual-result');assert.equal(valid.source.id,'actual-result');assert.equal(valid.resolvedFrom,'processor');
assert.equal(valid.connection.sourceHandle,'model');assert.equal(valid.connection.targetHandle,'model');
const changed=p=>planCanvasConnection(connection,[{...process,data:{...process.data,...p}},result,target],[]);
assert.match(changed({status:'running'}).error,/正在处理/);
assert.match(changed({status:'queued'}).error,/正在处理/);
assert.match(changed({status:'error'}).error,/已保存/);
assert.match(changed({resultAssetPath:null}).error,/已保存/);
assert.match(changed({nativeJobId:'future-job'}).error,/唯一/);
assert.ok(planCanvasConnection(connection,[process,target],[]).error);
assert.match(planCanvasConnection(connection,[...nodes,{...result,id:'duplicate'}],[]).error,/唯一/);
assert.ok(planCanvasConnection(connection,[process,{...result,data:{...result.data,status:'error'}},target],[]).error);
assert.ok(planCanvasConnection(connection,[process,{...result,data:{...result.data,assetPath:'assets/other.glb'}},target],[]).error);
assert.ok(planCanvasConnection(connection,[process,{...result,data:{...result.data,sourceNodeId:'other'}},target],[]).error);
const resolved=resolveConnectionSource(process,'model',nodes,[]).source;
process.data.resultAssetPath='assets/newer.glb';
assert.equal(resolved.data.assetPath,'assets/low.glb','existing reference stays frozen to actual result');
console.log('NATIVE3D_OUTPUT_CONNECTION_OK busy/missing/unique/ambiguous/current-job checks; source resolves to immutable actual result');

const high={id:'high',type:'native3d',data:{operation:'analyze',status:'completed',assetPath:'assets/high.glb'}};
const retry={id:'retry',type:'native3d',data:{operation:'source_lod',nativeParameters:{retryStage:'lod3'}}};
const highEdge={source:'high',sourceHandle:'model',target:'retry',targetHandle:'high'};
assert.equal(planCanvasConnection(highEdge,[high,retry],[]).connection.targetHandle,'high');
assert.ok(planCanvasConnection(highEdge,[high,{...retry,data:{operation:'source_lod'}}],[]).error);
assert.ok(planCanvasConnection(highEdge,[{...high,data:{...high.data,nativeUVPlan:{}}},retry],[]).error);
console.log('NATIVE3D_RETRY_HIGH_CONNECTION_OK manual high-port reconnect for bounded single-stage retry; unrelated operations/plans rejected');
