import assert from 'node:assert/strict';
globalThis.window = { location: { hostname: '127.0.0.1' } };
const api = await import('./src/workbench-api.js');
assert.equal(api.durationToFrames(5), 124);
assert.equal(api.durationToFrames(6), 141);
assert.equal(api.durationToFrames(15), 362);
for (const [ratio, [w, h]] of Object.entries(api.RATIOS)) {
  assert.ok(Math.abs(w * h - 400000) < 12000, `${ratio} pixel budget`);
  assert.equal(w % 32, 0); assert.equal(h % 32, 0);
}
const base = { prompt: 'test', ratio: '16:9', duration: 5, seed: 42, turbo: true };
const turbo = api.buildWorkflow(base);
assert.equal(turbo['11'].inputs.steps, 8);
assert.equal(turbo['11'].inputs.scheduler, 'beta');
assert.equal(turbo['3'].inputs.model[0], '2');
assert.equal(turbo['7'].inputs.length, 124);
const standard = api.buildWorkflow({ ...base, turbo: false });
assert.equal(standard['2'], undefined);
assert.equal(standard['3'].inputs.model[0], '1');
assert.equal(standard['11'].inputs.steps, 20);
assert.equal(standard['11'].inputs.scheduler, 'beta');
const image = api.buildWorkflow({ ...base, firstFrame: 'workbench/a.png', lastFrame: 'workbench/b.png' });
assert.deepEqual(image['7'].inputs.first_frame, ['17', 0]);
assert.deepEqual(image['7'].inputs.last_frame, ['18', 0]);
const files = api.extractVideos({ outputs: { '16': { videos: [{ filename: 'H3_Workbench_00001_.mp4', subfolder: 'video', type: 'output' }] } } });
assert.equal(files.length, 1);
assert.ok(files[0].url.includes('H3_Workbench_00001_.mp4'));
const swapOptions = {
  ...base, prompt: 'Female, short black bob hair, oval face, red jacket', preserveBackground: true,
  references: [{ kind: 'video', slot: 'guide', name: 'workbench/guide.mp4' }, { kind: 'image', slot: 'identity', name: 'workbench/identity.png' }],
};
const swap = api.buildCharacterSwapWorkflow(swapOptions);
assert.equal(swap.adapter.inputs.lora_name, 'h3_character_swap_v1.5.safetensors');
assert.equal(swap.turbo.inputs.lora_name, api.CHARACTER_SWAP_MODELS.turboLora);
assert.equal(swap.frames.inputs.length, 124);
assert.equal(swap.source_audio.class_type, 'TrimAudioDuration');
assert.equal(swap.source_audio.inputs.duration, 124 / 24);
assert.deepEqual(swap.reference_conditioning.inputs['ref_videos.ref_video_0'], ['window', 5]);
assert.deepEqual(swap.reference_conditioning.inputs['ref_images.ref_image_0'], ['reference', 0]);
assert.deepEqual(swap.reference_conditioning.inputs['ref_audios.ref_audio_0'], ['window', 6]);
assert.ok(swap.reference_conditioning.inputs.prompt.includes('complete reference character'));
assert.equal(swap.guider.inputs.cfg, 1);
assert.equal(swap.sampler.inputs.sampler_name, 'er_sde');
assert.equal(swap.schedule.inputs.scheduler, 'normal');
assert.equal(swap.schedule.inputs.steps, 8);
assert.equal(swap.edit_mask.class_type, 'H3RelayApplyEditMask');
assert.deepEqual(swap.edit_mask.inputs.source_latent, ['encode_source', 0]);
assert.deepEqual(swap.sample.inputs.latent_image, ['edit_mask', 0]);
assert.deepEqual(swap.video.inputs.audio, ['finish', 1]);
assert.equal(swap.finish.inputs.audio_mode, 'source');
assert.equal(swap.track.class_type, 'SAM3_VideoTrack');
assert.equal(swap.detect.inputs.threshold, 0.35);
assert.equal(swap.track.inputs.max_objects, 1);
assert.equal(swap.expand_mask.inputs.expansion_px, 64);
assert.equal(swap.select.inputs.selection, 'largest');
const rightSwap = api.buildCharacterSwapWorkflow({ ...swapOptions, targetSelection: 'rightmost' });
assert.equal(rightSwap.select.inputs.selection, 'rightmost');
const longSwap = api.buildCharacterSwapWorkflow({ ...swapOptions, duration: 10 });
assert.equal(longSwap.frames.inputs.length, 243);
assert.equal(longSwap.plan.inputs.source_frames, 243);
assert.equal(longSwap.start.class_type, 'StartLoop');
assert.equal(longSwap.end.class_type, 'EndLoop');
assert.equal(swap.refine_sample_2, undefined, 'Character swap only runs the first pass');
assert.equal(swap.save_pre, undefined, 'Character swap does not create a second video');
const hd = api.buildHdRefineWorkflow({
  ...base, resolution: '720P', fastAttention: true,
  references: [{ kind: 'video', slot: 'guide', name: 'workbench/first-pass.mp4' }, { kind: 'image', slot: 'identity', name: 'workbench/identity.png' }],
});
assert.equal(hd.upscale.class_type, 'MinimaxH3LatentUpscaler3D');
assert.equal(hd.upscale.inputs.model_name, api.HD_REFINE_MODEL);
assert.equal(hd.upscale.inputs['mode.width'], 1248);
assert.equal(hd.upscale.inputs['mode.height'], 736);
assert.deepEqual(hd.upscale.inputs.latent, ['encode_video', 0]);
assert.deepEqual(hd.highres_latent.inputs.video_latent, ['upscale', 0]);
assert.deepEqual(hd.highres_latent.inputs.audio_latent, ['encode_audio', 0]);
assert.deepEqual(hd.conditioning.inputs.length, ['probe', 3]);
assert.deepEqual(hd.conditioning.inputs['ref_images.ref_image_0'], ['identity', 0]);
assert.equal(hd.turbo.inputs.lora_name, api.HD_REFINE_TURBO);
assert.equal(hd.attention.class_type, 'MiniMaxH3MemoryEfficientSageAttentionPatch');
assert.deepEqual(hd.turbo.inputs.model, ['attention', 0]);
assert.equal(hd.schedule.inputs.steps, 3);
assert.equal(hd.schedule.inputs.scheduler, 'beta');
assert.equal(hd.schedule.inputs.denoise, 0.2);
assert.equal(hd.sampler.inputs.sampler_name, 'euler');
assert.deepEqual(hd.sample.inputs.latent_image, ['highres_latent', 0]);
assert.deepEqual(hd.video.inputs.audio, ['components', 1]);
assert.equal(hd.save.inputs.filename_prefix, 'video/H3_HD_Refine');
const noIdentity = api.buildHdRefineWorkflow({ ...base, resolution: '720P', fastAttention: false, references: [{ kind: 'video', slot: 'guide', name: 'workbench/first-pass.mp4' }] });
assert.equal(noIdentity.identity, undefined);
assert.equal(noIdentity.attention, undefined);
assert.deepEqual(noIdentity.turbo.inputs.model, ['shift', 0]);
console.log('API_TESTS_OK: durations, ratios, turbo, standard, frames, Akatz v1.5 single-pass swap, independent accelerated 720P latent HD refine');
